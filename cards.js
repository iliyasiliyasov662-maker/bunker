// Колоды карт «Бункера».
// Формат строки:  Текст карты | теги через запятую | строчка для эпилога (необязательно)
// В тексте можно писать {мужской|женский} вариант: «Служил{|а} в армии», «{он|она}».
// В эпилоге {name} заменяется на имя игрока.
// Теги навыков: med food water repair electric defense science morale leader tech build hunt chem rescue lang
// Плохие теги: danger thief glutton conflict lazy contagious dying terminal infertile weak
// Тег с минусом (-med) отнимает навык: врач с боязнью крови врачом уже не считается.

function parse(block, adult = false) {
  return block
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => {
      // делим по «|», но не внутри {мужской|женский}
      const parts = [''];
      let depth = 0;
      for (const ch of l) {
        if (ch === '{') depth++;
        if (ch === '}') depth--;
        if (ch === '|' && depth === 0) parts.push('');
        else parts[parts.length - 1] += ch;
      }
      const [t, tags = '', e = ''] = parts.map((s) => s.trim());
      return {
        t,
        tags: tags && tags !== '—' ? tags.split(',').map((s) => s.trim()).filter(Boolean) : [],
        e: e || null,
        adult,
      };
    });
}

